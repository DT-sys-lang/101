export class CmsFactValidationError extends Error {
  readonly path: string

  constructor(path: string, message: string) {
    super(`${path}: ${message}`)
    this.name = 'CmsFactValidationError'
    this.path = path
  }
}

export function normalizeAdapterConfig(options: CmsFactAdapterOptions = {}): AdapterConfig {
  const locales = toNonEmptyArray(options.locales?.length ? [...options.locales] : [...defaultCmsFactLocales], 'adapter.locales')
  const defaultLocale = options.defaultLocale ?? locales[0]

  if (!locales.includes(defaultLocale)) {
    reject('adapter.defaultLocale', `default locale '${defaultLocale}' is not present in locales`)
  }

  return {
    locales,
    defaultLocale,
    specificationRegistry: normalizeSpecificationRegistry(options.specificationRegistry ?? defaultSpecificationRegistry),
    validateSpecificationKeys: options.validateSpecificationKeys ?? true,
  }
}

export function normalizeCmsFactInput(value: unknown, options: CmsFactAdapterOptions = {}): CmsFactInput {
  const config = normalizeAdapterConfig(options)
  assertObject(value, 'cmsFacts')
  rejectUnknownFields(value, ['categoryFacts', 'productFacts'], 'cmsFacts')
  rejectIllegalFields(value, ['categoryTree', 'products', 'canonical', 'slug', 'categoryPath', 'seo', 'geoAi', 'geo', 'jsonld', 'jsonLd', 'jsonLD'], 'cmsFacts')

  assertArray(value.categoryFacts, 'cmsFacts.categoryFacts')
  assertArray(value.productFacts, 'cmsFacts.productFacts')

  const categoryFacts = value.categoryFacts.map((fact, index) => {
    assertCategoryFact(fact, `cmsFacts.categoryFacts[${index}]`, config.locales)
    return fact
  })
  const productFacts = value.productFacts.map((fact, index) => {
    const productFact = normalizeProductFact(fact, `cmsFacts.productFacts[${index}]`, config.locales)
    validateProductSpecificationKeys(productFact.specificationGroups, config.specificationRegistry, config.validateSpecificationKeys, `cmsFacts.productFacts[${index}].specificationGroups`)
    return productFact
  })

  return {
    categoryFacts,
    productFacts,
  }
}

