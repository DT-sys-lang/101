export function toNonEmptyArray<T>(values: readonly T[] | undefined, path: string): NonEmptyReadonlyArray<T> {
  if (!values?.length) {
    reject(path, 'expected a non-empty array')
  }

  return values as NonEmptyReadonlyArray<T>
}

export function normalizeSlug(value: string): SlugSegment | '' {
  const slug = value
    .trim()
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

  return slug as SlugSegment | ''
}

