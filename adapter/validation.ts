function validateCategoryCycles(facts: readonly CategoryFact[], byId: ReadonlyMap<CategoryId, CategoryFact>) {
  const visiting = new Set<CategoryId>()
  const visited = new Set<CategoryId>()

  function visit(fact: CategoryFact) {
    if (visited.has(fact.id)) {
      return
    }

    if (visiting.has(fact.id)) {
      reject(`categoryFacts.${fact.id}.parentId`, 'category parent graph contains a cycle')
    }

    visiting.add(fact.id)

    if (fact.parentId) {
      const parent = byId.get(fact.parentId)

      if (parent) {
        visit(parent)
      }
    }

    visiting.delete(fact.id)
    visited.add(fact.id)
  }

  facts.forEach(visit)
}

function validateSiblingCategorySlugs(childrenByParentId: ReadonlyMap<CategoryId | null, readonly CategoryFact[]>, locale: LocaleCode) {
  for (const [parentId, children] of childrenByParentId.entries()) {
    const slugs = new Set<SlugSegment>()

    for (const child of children) {
      const slug = normalizeSlug(localizeFactText(child.name, locale))

      if (!slug) {
        reject(`categoryFacts.${child.id}.name.${locale}`, 'category name did not produce a valid slug')
      }

      if (slugs.has(slug)) {
        reject(`categoryFacts.${parentId ?? 'root'}.children`, `duplicate generated sibling slug '${slug}'`)
      }

      slugs.add(slug)
    }
  }
}

function flattenCategoryNodes(root: CategoryNode): readonly CategoryNode[] {
  return [root, ...(root.children ?? []).flatMap((child) => flattenCategoryNodes(child))]
}

function rejectUnknownFields(value: Record<string, unknown>, allowedFields: readonly string[], path: string) {
  for (const key of Object.keys(value)) {
    if (!allowedFields.includes(key)) {
      reject(`${path}.${key}`, 'field is not allowed in CMS Fact input')
    }
  }
}

function rejectIllegalFields(value: unknown, illegalFields: readonly string[], path: string) {
  assertObject(value, path)

  for (const field of illegalFields) {
    if (hasNestedField(value, field.split('.'))) {
      reject(`${path}.${field}`, 'field is derived by the adapter and must not be provided by CMS')
    }
  }
}

function hasNestedField(value: unknown, pathParts: readonly string[]): boolean {
  if (!pathParts.length) {
    return true
  }

  if (!value || typeof value !== 'object') {
    return false
  }

  const [head, ...tail] = pathParts

  if (!Object.prototype.hasOwnProperty.call(value, head)) {
    return false
  }

  return tail.length === 0 || hasNestedField((value as Record<string, unknown>)[head], tail)
}

