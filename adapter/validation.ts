export function validateCategoryFacts(facts: readonly CategoryFact[], options: CmsFactAdapterOptions = {}): CategoryFactGraph {
  const config = normalizeAdapterConfig(options)

  if (facts.length === 0) {
    reject('categoryFacts', 'at least one category fact is required')
  }

  const byId = new Map<CategoryId, CategoryFact>()
  const childrenByParentId = new Map<CategoryId | null, CategoryFact[]>()

  facts.forEach((fact, index) => {
    const path = `categoryFacts[${index}]`
    assertCategoryFact(fact, path, config.locales)

    if (byId.has(fact.id)) {
      reject(`${path}.id`, `duplicate category id '${fact.id}'`)
    }

    byId.set(fact.id, fact)
    const children = childrenByParentId.get(fact.parentId) ?? []
    children.push(fact)
    childrenByParentId.set(fact.parentId, children)
  })

  const rootFacts = childrenByParentId.get(null) ?? []

  if (rootFacts.length !== 1) {
    reject('categoryFacts', `expected exactly one root category, found ${rootFacts.length}`)
  }

  for (const fact of facts) {
    if (fact.parentId && !byId.has(fact.parentId)) {
      reject(`categoryFacts.${fact.id}.parentId`, `unknown parent '${fact.parentId}'`)
    }
  }

  validateCategoryCycles(facts, byId)
  validateSiblingCategorySlugs(childrenByParentId, config.defaultLocale)

  const depthById = new Map<CategoryId, number>()

  function resolveDepth(fact: CategoryFact, stack: readonly CategoryId[] = []): number {
    const existingDepth = depthById.get(fact.id)

    if (existingDepth !== undefined) {
      return existingDepth
    }

    if (!fact.parentId) {
      depthById.set(fact.id, 0)
      return 0
    }

    if (stack.includes(fact.id)) {
      reject(`categoryFacts.${fact.id}.parentId`, 'category parent graph contains a cycle')
    }

    const parent = byId.get(fact.parentId)

    if (!parent) {
      reject(`categoryFacts.${fact.id}.parentId`, `unknown parent '${fact.parentId}'`)
    }

    const depth = resolveDepth(parent, [...stack, fact.id]) + 1

    if (depth > 4) {
      reject(`categoryFacts.${fact.id}.parentId`, `category depth ${depth} exceeds domain max depth 4`)
    }

    depthById.set(fact.id, depth)
    return depth
  }

  for (const fact of facts) {
    resolveDepth(fact)
  }

  return {
    rootFact: rootFacts[0],
    byId,
    childrenByParentId,
    depthById,
  }
}

export function validateProductFactsAgainstCategoryTree(
  facts: readonly ProductFact[],
  categoryTree: CategoryTree,
  options: CmsFactAdapterOptions = {},
) {
  const config = normalizeAdapterConfig(options)
  const categoryIds = new Set(flattenCategoryNodes(categoryTree.root).map((category) => category.id))

  facts.forEach((fact, index) => {
    const path = `productFacts[${index}]`
    assertProductFact(fact, path, config.locales)
    validateProductSpecificationKeys(fact.specificationGroups, config.specificationRegistry, config.validateSpecificationKeys, `${path}.specificationGroups`)

    if (!categoryIds.has(fact.primaryCategoryId)) {
      reject(`${path}.primaryCategoryId`, `unknown category '${fact.primaryCategoryId}'`)
    }

    const allCategoryIds = [fact.primaryCategoryId, ...(fact.additionalCategoryIds ?? [])]
    const uniqueCategoryIds = new Set(allCategoryIds)

    if (uniqueCategoryIds.size !== allCategoryIds.length) {
      reject(`${path}.additionalCategoryIds`, 'product category assignments contain duplicates')
    }

    for (const categoryId of fact.additionalCategoryIds ?? []) {
      if (!categoryIds.has(categoryId)) {
        reject(`${path}.additionalCategoryIds`, `unknown category '${categoryId}'`)
      }
    }

    const measuredKinds = new Set((fact.measurements ?? []).map((measurement) => measurement.kind))

    for (const measurementKind of fact.measurementKinds) {
      if (!measuredKinds.has(measurementKind)) {
        reject(`${path}.measurementKinds`, `measurement kind '${measurementKind}' has no matching measurement record`)
      }
    }
  })
}

export function validateProductIdentityConsistency(facts: readonly ProductFact[]) {
  const ids = new Set<ProductId>()
  const skus = new Set<string>()
  const modelSlugs = new Map<SlugSegment, ProductId>()

  facts.forEach((fact, index) => {
    const path = `productFacts[${index}]`
    assertProductFact(fact, path)

    if (ids.has(fact.id)) {
      reject(`${path}.id`, `duplicate product id '${fact.id}'`)
    }

    if (skus.has(fact.sku)) {
      reject(`${path}.sku`, `duplicate product sku '${fact.sku}'`)
    }

    const modelSlug = normalizeSlug(fact.model)

    if (!modelSlug) {
      reject(`${path}.model`, 'model did not produce a valid product slug')
    }

    const ownerProductId = modelSlugs.get(modelSlug)

    if (ownerProductId && ownerProductId !== fact.id) {
      reject(`${path}.model`, `generated model slug '${modelSlug}' conflicts with product '${ownerProductId}'`)
    }

    ids.add(fact.id)
    skus.add(fact.sku)
    modelSlugs.set(modelSlug, fact.id)
  })
}

